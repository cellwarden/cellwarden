# Regenerates loess_interpolate.tsv, the reference for the `loess_interpolate_matches_r`
# test in rust/scfast-core/tests/loess.rs. Run from the repository root:
#
#   Rscript rust/scfast-core/tests/data/make_loess_fixture.R
#
# R's default loess(y ~ x, span, degree = 2) (surface = "interpolate", cell = 0.2), as
# FindVariableFeatures(vst) calls it. Two cases: a mean-variance-like cloud with tied x
# (span 0.3, Seurat's default) and a small unsorted set (span 0.75).
out <- "rust/scfast-core/tests/data/loess_interpolate.tsv"
set.seed(7)
x1 <- c(runif(380, -3, 1.5), rep(-2.5, 12), rep(0, 8))
y1 <- 0.9 * x1 + 0.3 * sin(3 * x1) + rnorm(400, sd = 0.25)
x2 <- sample(rnorm(60))
y2 <- x2^2 + rnorm(60, sd = 0.1)
case <- function(id, x, y, span) {
  f <- fitted(loess(y ~ x, span = span, degree = 2))
  data.frame(case = id, span = span, x = sprintf("%.17g", x), y = sprintf("%.17g", y), fitted = sprintf("%.17g", f))
}
header <- sprintf("# R %s; generated by make_loess_fixture.R", paste(R.version$major, R.version$minor, sep = "."))
writeLines(header, out)
suppressWarnings(write.table(rbind(case(1, x1, y1, 0.3), case(2, x2, y2, 0.75)), out, sep = "\t", quote = FALSE,
                             row.names = FALSE, append = TRUE))
