# Regenerates the Seurat reference used by the `seurat_parity_pbmc_like` test in
# rust/scfast-core/tests/pca.rs. Run from the repository root:
#
#   Rscript rust/scfast-core/tests/data/make_seurat_pca_fixture.R
#
# Pipeline (as seurat_pbmc3k.R / bench/run_seurat.R): NormalizeData (LogNormalize, 1e4) ->
# FindVariableFeatures (vst, nfeatures = 2000, i.e. all 800 genes here) -> ScaleData ->
# RunPCA (npcs = 30, seed.use = 0), once with the default scale.max = 10 and once with
# scale.max = Inf (no clipping, which the implicit operator reproduces exactly).
#
# Writes, next to this script:
#   pbmc_like_hvg.txt          0-based row of each HVG in matrix.mtx, in VariableFeatures order
#   pbmc_like_seurat_stdev.tsv Stdev of PCs 1-30 for both runs
#   pbmc_like_seurat_pcs.tsv   cell embeddings, PCs 1-10 for both runs (500 rows)
suppressPackageStartupMessages({ library(Seurat); library(Matrix) })
fixture <- "tests/fixtures/pbmc_like"
out <- "rust/scfast-core/tests/data"
m <- as(as(readMM(file.path(fixture, "matrix.mtx")), "CsparseMatrix"), "dgCMatrix")
feats <- read.delim(file.path(fixture, "features.tsv"), header = FALSE, colClasses = "character", quote = "")
dimnames(m) <- list(make.unique(feats[[2]]), readLines(file.path(fixture, "barcodes.tsv")))
obj <- CreateSeuratObject(m, min.cells = 0, min.features = 0)
obj <- NormalizeData(obj, normalization.method = "LogNormalize", scale.factor = 1e4, verbose = FALSE)
obj <- FindVariableFeatures(obj, selection.method = "vst", nfeatures = 2000, verbose = FALSE)
hvg <- VariableFeatures(obj)
run <- function(scale.max) {
  o <- ScaleData(obj, features = hvg, scale.max = scale.max, verbose = FALSE)
  RunPCA(o, features = hvg, npcs = 30, seed.use = 0, verbose = FALSE)[["pca"]]
}
clip <- run(10)
noclip <- run(Inf)
header <- sprintf("# R %s, Seurat %s; generated by make_seurat_pca_fixture.R",
                  paste(R.version$major, R.version$minor, sep = "."), packageVersion("Seurat"))
writeLines(c(header, paste(match(hvg, rownames(obj)) - 1L, collapse = " ")), file.path(out, "pbmc_like_hvg.txt"))
fmt <- function(x) formatC(x, digits = 8, format = "g")
st <- data.frame(pc = 1:30, clip10 = fmt(Stdev(clip)), noclip = fmt(Stdev(noclip)))
writeLines(header, file.path(out, "pbmc_like_seurat_stdev.tsv"))
suppressWarnings(write.table(st, file.path(out, "pbmc_like_seurat_stdev.tsv"), sep = "\t", quote = FALSE,
                             row.names = FALSE, append = TRUE))
e <- cbind(Embeddings(clip)[, 1:10], Embeddings(noclip)[, 1:10])
pcs <- as.data.frame(apply(e, 2, fmt))
names(pcs) <- c(paste0("clip10_PC", 1:10), paste0("noclip_PC", 1:10))
writeLines(header, file.path(out, "pbmc_like_seurat_pcs.tsv"))
suppressWarnings(write.table(pcs, file.path(out, "pbmc_like_seurat_pcs.tsv"), sep = "\t", quote = FALSE,
                             row.names = FALSE, append = TRUE))
